import type { DraftStatus } from "../../../contracts/draft.ts";
import { cx } from "../../../lib/cx.ts";
import { formatPartialDate } from "../../../lib/datePrecision.ts";
import { Badge } from "../../basics/Badge/Badge.tsx";

/** The Entry's draft status as listed: 抽取中 shows as 待确认 until it settles. */
export type EntryStatus = Exclude<DraftStatus, "extracting">;

export type EntryListItemProps = {
  /** 记录原文 */
  text: string;
  /** 发生日期, contract form "2015" | "2015-06" | "2026-11-16". */
  occurredOn: string;
  today: Date;
  status: EntryStatus;
  /** Number of facts the Entry produced. */
  itemCount?: number;
  /** 补记: written later than it happened. */
  backfilled?: boolean;
  /** A 手动编辑记录 generated by editing the profile directly. */
  manual?: boolean;
  onClick?: () => void;
  className?: string;
};

/**
 * DESIGN.md uses text-disabled for 已放弃; that grey fails the 4.5:1 body-text contrast
 * (AC-UI-9), so it reads text-secondary here; the word itself carries the state.
 */
const STATUS: Record<EntryStatus, { label: string; color: string }> = {
  confirmed: { label: "已确认", color: "text-neutral-text-secondary" },
  pending: { label: "待确认", color: "text-status-error-6" },
  discarded: { label: "已放弃", color: "text-neutral-text-secondary" },
  failed: { label: "整理失败", color: "text-status-error-6" },
};

/** 记录列表行: text clamped to two lines + date (with precision) + facts count + status. */
export function EntryListItem({
  text,
  occurredOn,
  today,
  status,
  itemCount,
  backfilled,
  manual,
  onClick,
  className,
}: EntryListItemProps) {
  const meta = [
    formatPartialDate(occurredOn, today),
    itemCount !== undefined ? `${itemCount} 条信息` : null,
    backfilled ? "补记" : null,
    manual ? "手动编辑" : null,
  ]
    .filter(Boolean)
    .join(" · ");
  const s = STATUS[status];
  return (
    <button
      type="button"
      onClick={onClick}
      className={cx(
        "motion-colors focus-ring flex w-full cursor-pointer items-start gap-sm px-md py-sm text-left hover:bg-neutral-bg-subtle",
        className,
      )}
    >
      <span className="flex min-w-[0] flex-1 flex-col gap-xs">
        <span data-entry-text="" className="line-clamp-2 text-body-md text-neutral-text-primary">
          {text}
        </span>
        <span className="text-caption text-neutral-text-secondary">{meta}</span>
      </span>
      <span
        data-entry-status={status}
        className={cx("flex shrink-0 items-center gap-xs text-caption", s.color)}
      >
        {s.label}
        {status === "pending" && <Badge variant="dot" label="有待确认的草稿" />}
      </span>
    </button>
  );
}
